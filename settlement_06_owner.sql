------------------------------------------------------------------------------
-- Schema: the owner/operator discriminator
------------------------------------------------------------------------------

-- NOT NULL with a default of COMPANY. Every driver already in the table is a
-- company driver, and leaving the column nullable would mean every query
-- downstream has to decide what NULL means.
IF COL_LENGTH(N'dbo.Drivers', N'driver_type') IS NULL
BEGIN
    ALTER TABLE dbo.Drivers ADD driver_type VARCHAR(10) NOT NULL
        CONSTRAINT DF_Drivers_type DEFAULT 'COMPANY';
END
GO

-- How an owner/operator is paid: by the mile, or as a share of what the load
-- billed. NULL for a company driver -- the question does not apply to them,
-- and a default of MILEAGE would be a fact nobody asserted.
IF COL_LENGTH(N'dbo.Drivers', N'pay_basis') IS NULL
BEGIN
    ALTER TABLE dbo.Drivers ADD pay_basis VARCHAR(12) NULL;
END
GO

IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = N'CK_Drivers_type')
BEGIN
    ALTER TABLE dbo.Drivers ADD CONSTRAINT CK_Drivers_type
        CHECK (driver_type IN ('COMPANY', 'OWNER'));
END
GO

-- An owner has a pay basis and a company driver does not. Stating it here
-- means the front end can branch on driver_type alone and trust that
-- pay_basis is there when it needs it.
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = N'CK_Drivers_paybasis')
BEGIN
    ALTER TABLE dbo.Drivers ADD CONSTRAINT CK_Drivers_paybasis CHECK (
        (driver_type = 'OWNER'   AND pay_basis IN ('MILEAGE', 'PERCENTAGE'))
        OR
        (driver_type = 'COMPANY' AND pay_basis IS NULL)
    );
END
GO

-- The truck. A company driver is assigned whatever is in the yard; an owner
-- /operator's statement names the specific vehicle, because it is theirs and
-- the truck payment on the deduction side is for this one.
IF COL_LENGTH(N'dbo.Drivers', N'unit_no') IS NULL
BEGIN
    ALTER TABLE dbo.Drivers ADD unit_no VARCHAR(20) NULL;
END
GO

IF COL_LENGTH(N'dbo.Drivers', N'truck_description') IS NULL
BEGIN
    ALTER TABLE dbo.Drivers ADD truck_description NVARCHAR(80) NULL;
END
GO

-- What the load billed the customer. A percentage driver's pay is a share of
-- this, so without it their pay_amount is a number nobody can check. NULL for
-- a mileage line, where miles x rate is already the whole story.
IF COL_LENGTH(N'dbo.SettlementRoutes', N'linehaul_revenue') IS NULL
BEGIN
    ALTER TABLE dbo.SettlementRoutes ADD linehaul_revenue DECIMAL(12,2) NULL;
END
GO

IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = N'CK_Routes_linehaul')
BEGIN
    ALTER TABLE dbo.SettlementRoutes ADD CONSTRAINT CK_Routes_linehaul
        CHECK (linehaul_revenue IS NULL OR linehaul_revenue >= 0);
END
GO

------------------------------------------------------------------------------
-- Escrow / loan balances
--
-- One row per account per settlement -- a running statement of an account the
-- carrier holds on the driver's behalf, not a balance the driver can spend.
--
-- The CHECK is the point of the table. The original printed BEGINNING_BALANCE,
-- TRANSACTION_AMOUNT and CURRENT_BALANCE as three independent columns with
-- nothing tying them together, so a bad feed showed a driver an ending balance
-- that did not follow from the change above it. Here that row cannot be
-- written.
------------------------------------------------------------------------------
IF OBJECT_ID(N'dbo.SettlementEscrow', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SettlementEscrow (
        escrow_id          INT IDENTITY(1,1) NOT NULL,
        settlement_id      INT           NOT NULL,
        escrow_code        VARCHAR(20)   NOT NULL,
        description        NVARCHAR(120) NOT NULL,

        beginning_balance  DECIMAL(12,2) NOT NULL,
        -- Signed the way it moves the balance: a contribution is positive, a
        -- refund or a repair drawn against the account is negative.
        transaction_amount DECIMAL(12,2) NOT NULL,
        current_balance    DECIMAL(12,2) NOT NULL,

        CONSTRAINT PK_SettlementEscrow PRIMARY KEY (escrow_id),
        CONSTRAINT FK_Escrow_settlement FOREIGN KEY (settlement_id)
            REFERENCES dbo.Settlements (settlement_id) ON DELETE CASCADE,
        -- One row per account per settlement. Two would mean two ending
        -- balances for the same account on the same day.
        CONSTRAINT UQ_Escrow_settlement_code UNIQUE (settlement_id, escrow_code),
        CONSTRAINT CK_Escrow_chain
            CHECK (current_balance = beginning_balance + transaction_amount)
    );

    CREATE INDEX IX_Escrow_settlement ON dbo.SettlementEscrow (settlement_id);
END
GO

