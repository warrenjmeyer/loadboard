-- settlement_06_owner.sql
-- Owner/operator settlements: the port of ownDrvSettlement.cfm.
--
-- An owner/operator is a 1099 contractor who owns the truck. The money moves
-- differently enough from a company driver that the statement is a different
-- document: fuel, the truck payment and its insurance all come OUT of the
-- settlement, nothing is withheld for tax, and the driver is carrying escrow
-- balances the carrier holds on their behalf. What is the same -- earnings by
-- load, revenue and deduction lines -- reuses the existing tables rather than
-- getting parallel ones, because the original's separate OWNER_OPERATOR_*
-- tables held the same columns as the company ones under different names.
--
-- Three things this file adds to the schema:
--   1. dbo.Drivers.driver_type    -- COMPANY or OWNER, the discriminator
--   2. dbo.Drivers.pay_basis      -- MILEAGE or PERCENTAGE, owners only
--   3. dbo.SettlementEscrow       -- the escrow/loan balances
--
-- Generated, not hand-written: route pay is miles x rate (or linehaul revenue
-- x share) to the cent, and each escrow row's ending balance is its own
-- beginning plus its own transaction -- enforced by a CHECK, because three
-- unrelated numbers in three columns is exactly what the original printed.
--
--   DO NOT EDIT THIS FILE BY HAND.
--   tools/gen_owner_settlements.mjs is the source; regenerate with
--       node tools/gen_owner_settlements.mjs > settlement_06_owner.sql
--   A figure changed here and not there is one the arithmetic no longer
--   guarantees, which is the whole reason the file is generated.
--
-- Re-runnable. Requires settlement_01_ddl.sql and settlement_05_link.sql.

SET NOCOUNT ON;
