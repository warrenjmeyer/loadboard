-- What just landed
------------------------------------------------------------------------------
SELECT d.driver_code, d.pay_basis,
       CONVERT(char(10), s.check_date, 120) AS check_date,
       r.route_pay, l.line_total,
       r.route_pay + l.line_total AS settlement_total,
       e.escrow_balance
FROM dbo.Settlements AS s
JOIN dbo.Drivers AS d ON d.driver_code = s.driver_code
CROSS APPLY (SELECT COALESCE(SUM(pay_amount), 0) AS route_pay
             FROM dbo.SettlementRoutes WHERE settlement_id = s.settlement_id) AS r
CROSS APPLY (SELECT COALESCE(SUM(amount), 0) AS line_total
             FROM dbo.SettlementLines WHERE settlement_id = s.settlement_id) AS l
CROSS APPLY (SELECT COALESCE(SUM(current_balance), 0) AS escrow_balance
             FROM dbo.SettlementEscrow WHERE settlement_id = s.settlement_id) AS e
WHERE d.driver_type = 'OWNER'
ORDER BY d.driver_code, s.check_date DESC;
